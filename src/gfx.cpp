/* Bytes 1..31 and 128..255, measured from the oracle's screen RAM
   (tools/gen_font.py). Wide glyphs are real 7x5 bitmaps, not scaled. */
#include "font_table.inc"

void pico8_draw_char(int x, int y, uint8_t ch, uint8_t color)
{
    if (x >= PICO8_SCREEN_W || y >= PICO8_SCREEN_H) return;
    if (x + 8 <= 0 || y + 8 <= 0) return;

    /* print() observes the draw palette. */
    color = pico8_ram[PICO8_DRAW_STATE + (color & 0x0f)] & 0x0f;

    const uint8_t *glyph;
    int cols = 4;
    if (ch >= 32 && ch <= 127) {
        glyph = pico8_font[ch - 32];
    } else if (ch >= 128) {
        glyph = pico8_font_wide[ch - 128];
        cols = 8;
    } else if (ch >= 16) {
        glyph = pico8_font_small[ch - 16];
    } else if (ch >= 1) {
        glyph = pico8_font_ctrl[ch - 1];
    } else {
        return;                 /* code 0 ends the string: nothing to draw */
    }

    for (int row = 0; row < 6; row++) {
        if (y + row < 0 || y + row >= PICO8_SCREEN_H) continue;
        uint8_t bits = glyph[row];
        for (int col = 0; col < cols; col++) {
            if (x + col < 0 || x + col >= PICO8_SCREEN_W) continue;
            if (bits & (1 << (7 - col))) {
                int px = x + col;
                uint16_t addr = PICO8_SCREEN + (uint16_t)(y + row) * 64 + (uint16_t)(px >> 1);
                if (px & 1) {
                    pico8_ram[addr] = (pico8_ram[addr] & 0x0f) | (color << 4);
                } else {
                    pico8_ram[addr] = (pico8_ram[addr] & 0xf0) | color;
                }
            }
        }
    }
}

/*
** One p8scii text cell, as print() draws it. Altogether the modes measured on
** the oracle:
**   - background colours fill a cell one pixel bigger than the glyph on the
**     top/left and the right/bottom, i.e. (advance+1) by (6 glyph rows + 1);
**   - \^w doubles the cell horizontally, \^t vertically (both for \^p);
**   - in inverted mode the cell is filled with the foreground colour and the
**     glyph itself is drawn in the background colour -- or left untouched
**     when no background colour is set;
**   - pinball mode spreads the glyph over a double-width/tall cell but keeps
**     single pixels, offset by one pixel to the right.
*/
void pico8_draw_char_text(int x, int y, uint8_t ch,
                          uint8_t fg, int has_bg, uint8_t bg,
                          int invert, int wide, int tall, int pinball)
{
    const uint8_t *glyph;
    int cols = 4;
    if (ch >= 32 && ch <= 127) {
        glyph = pico8_font[ch - 32];
    } else if (ch >= 128) {
        glyph = pico8_font_wide[ch - 128];
        cols = 8;
    } else if (ch >= 16) {
        glyph = pico8_font_small[ch - 16];
    } else if (ch >= 1) {
        glyph = pico8_font_ctrl[ch - 1];
        cols = 3;
    } else {
        return;
    }

    int sx = (wide || pinball) ? 2 : 1;
    int sy = (tall || pinball) ? 2 : 1;

    fg = pico8_ram[PICO8_DRAW_STATE + (fg & 0x0f)] & 0x0f;
    bg = pico8_ram[PICO8_DRAW_STATE + (bg & 0x0f)] & 0x0f;

    int glyph_w = cols * sx, glyph_h = 6 * sy;

    /* Fill the cell, leaving the glyph's own ink positions alone so that
       inverted text without a background colour keeps the screen showing
       through the letter. */
    if (has_bg || invert) {
        uint8_t fill = invert ? fg : bg;
        uint8_t ink = invert ? bg : fg;
        int ink_on = !invert || has_bg;
        for (int ry = -sy; ry < 6 * sy; ry++) {
            for (int rx = -sx; rx < cols * sx; rx++) {
                int gx = rx, gy = ry;
                int covered = 0;
                if (gx >= 0 && gy >= 0 && gx < glyph_w && gy < glyph_h) {
                    int col = gx / sx, row = gy / sy;
                    if (pinball) {
                        col = (gx - 1) / 2;
                        row = gy / 2;
                        covered = (gx == 1 + col * 2) && (gy == row * 2);
                    } else {
                        covered = 1;
                    }
                    if (covered && (col < 0 || col >= cols ||
                                    !(glyph[row] & (1 << (7 - col)))))
                        covered = 0;
                }
                if (covered) {
                    if (ink_on) pico8_put_pixel(x + rx, y + ry, ink);
                } else {
                    pico8_put_pixel(x + rx, y + ry, fill);
                }
            }
        }
    }

    if (invert && !has_bg) return;      /* ink is the (transparent) screen */

    uint8_t ink = invert ? bg : fg;
    for (int row = 0; row < 6; row++) {
        uint8_t bits = glyph[row];
        if (!bits) continue;
        for (int col = 0; col < cols; col++) {
            if (!(bits & (1 << (7 - col)))) continue;
            if (pinball) {
                pico8_put_pixel(x + 1 + col * 2, y + row * 2, ink);
            } else {
                for (int ry = 0; ry < sy; ry++)
                    for (int rx = 0; rx < sx; rx++)
                        pico8_put_pixel(x + col * sx + rx, y + row * sy + ry,
                                        ink);
            }
        }
    }
}

void pico8_blit_char(uint8_t ch, int x, int y, uint8_t color)
{
    pico8_draw_char(x, y, ch, color);
}

void pico8_put_pixel(int x, int y, uint8_t color)
{
    if (x < 0 || x >= PICO8_SCREEN_W || y < 0 || y >= PICO8_SCREEN_H) return;
    uint16_t addr = PICO8_SCREEN + (uint16_t)y * 64 + (uint16_t)(x >> 1);
    if (x & 1) pico8_ram[addr] = (pico8_ram[addr] & 0x0f) | (uint8_t)((color & 0x0f) << 4);
    else       pico8_ram[addr] = (pico8_ram[addr] & 0xf0) | (uint8_t)(color & 0x0f);
}

void pico8_clear_screen(uint8_t color)
{
    uint8_t nib = (uint8_t)(color & 0x0f);
    uint8_t byte = (uint8_t)(nib | (nib << 4));
    memset(&pico8_ram[PICO8_SCREEN], byte, 0x2000);
}

void pico8_draw_char_scaled(int x, int y, uint8_t ch, uint8_t color, int scale)
{
    if (scale < 1) scale = 1;
    const uint8_t *glyph = (ch >= 32 && ch <= 127) ? pico8_font[ch - 32] : pico8_font[0];

    for (int row = 0; row < 6; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 4; col++) {
            if (!(bits & (1 << (7 - col)))) continue;
            for (int sy = 0; sy < scale; sy++)
                for (int sx = 0; sx < scale; sx++)
                    pico8_put_pixel(x + col * scale + sx, y + row * scale + sy, color);
        }
    }
}

void pico8_render_screen(uint32_t *pixels, int pitch, int scale_w)
{
    int screen_pitch = pitch / (int)sizeof(uint32_t);

    for (int y = 0; y < PICO8_SCREEN_H; y++) {
        uint32_t *row = pixels + y * screen_pitch * scale_w;
        for (int x = 0; x < PICO8_SCREEN_W; x++) {
            uint16_t addr = PICO8_SCREEN + (uint16_t)y * 64 + (uint16_t)(x >> 1);
            uint8_t byte = pico8_ram[addr];
            uint8_t col_idx = (x & 1) ? (byte >> 4) : (byte & 0x0f);

            uint8_t screen_pal = pico8_ram[PICO8_DRAW_STATE + 0x10 + col_idx] & 0x0f;
            uint32_t rgb = pico8_palette[screen_pal];

            for (int sy = 0; sy < scale_w; sy++) {
                for (int sx = 0; sx < scale_w; sx++) {
                    row[x * scale_w + sx + sy * screen_pitch] = rgb;
                }
            }
        }
    }
}
