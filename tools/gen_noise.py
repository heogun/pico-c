#!/usr/bin/env python3
"""gen_noise.py — build src/noise_table.inc from PICO-8's own .wav export.

PICO-8's noise (waveform 6) gets brighter and louder as the key rises.  Its
samples are random, so they cannot be matched one by one; what pico-c
matches is the spectrum.  For every key the noise is modelled as

    out = g * (lowpass(r) + m * r),   lowpass: y += k * (r - y)

where r is white noise, uniform in -1..1, at 22050Hz.  This tool fits k, m
and g for each of the 64 keys to the spectrum PICO-8 produces.

Two steps (needs numpy and scipy):

    tools/gen_noise.py cart noise.p8
        writes a cart whose sound effect N plays the noise at key N,
        volume 7, speed 32, and exports them with export("noise_%d.wav").
        Run it in a windowed PICO-8 with its own home folder (see
        platforms/macos/oracle_audio.sh).

    tools/gen_noise.py table <dir with noise_N.wav> > src/noise_table.inc
        fits the model to the spectrum (Welch, 512 points) of every file,
        and sets its level from the measured RMS.
        The output is in the units of pico8_wave(): a triangle at full
        volume peaks at 0.5.

gen_noise.py — PICO-8 자체의 .wav export로 src/noise_table.inc를 만든다.

PICO-8의 노이즈(파형 6)는 키가 높을수록 밝고 커진다. 샘플은 무작위라 하나씩
맞출 수 없으므로 pico-c는 스펙트럼을 맞춘다. 키마다 노이즈를
out = g * (lowpass(r) + m * r) (r은 22050Hz의 -1..1 균일 백색 잡음)로 보고,
PICO-8이 내는 스펙트럼에 k, m, g를 맞춘다. "cart" 단계는 효과음 N이 키 N의
노이즈를 내보내는 카트를 쓰고, "table" 단계는 파일마다 모델을 맞춘다
(numpy, scipy 필요).
"""
import sys
import wave

RATE = 22050
PEAK = 16122.0          # a full volume triangle in PICO-8's .wav files

def write_cart(path):
    lines = []
    for key in range(64):
        notes = [(key, 6, 7, 0)] + [(0, 0, 0, 0)] * 31
        lines.append('%02x%02x%02x%02x' % (0, 32, 0, 0) +
                     ''.join('%02x%x%x%x' % n for n in notes))
    with open(path, 'w') as f:
        f.write('pico-8 cartridge // http://www.pico-8.com\nversion 43\n'
                '__lua__\nexport("noise_%d.wav")\n__sfx__\n' + '\n'.join(lines) + '\n')

def fit(path):
    import numpy as np
    from scipy.optimize import least_squares
    from scipy.signal import welch

    w = wave.open(path)
    x = np.frombuffer(w.readframes(w.getnframes()), dtype='<i2').astype(float)
    x = x[300:5700] / PEAK * 0.5
    f, p = welch(x, RATE, nperseg=512)
    keep = f > 30
    f, p = f[keep], p[keep]

    def residual(q):
        k, m, g = q
        z = np.exp(-2j * np.pi * f / RATE)
        h = g * (k / (1 - (1 - k) * z) + m)
        return np.log(np.abs(h) ** 2 / 3 / (RATE / 2) + 1e-20) - np.log(p + 1e-20)

    best = None
    for k0 in (0.02, 0.1, 0.3, 0.7):
        for m0 in (0.0, 0.1, 0.5):
            sol = least_squares(residual, [k0, m0, 0.5],
                                bounds=([1e-4, 0, 1e-3], [1, 5, 20]))
            if best is None or sol.cost < best.cost:
                best = sol
    k, m, g = best.x

    # The spectrum says little about the lowest frequencies, which carry
    # most of the power at low keys: set the level from the measured RMS.
    # 스펙트럼은 가장 낮은 주파수를 잘 못 보는데, 낮은 키에서는 그곳에 힘이
    # 몰려 있다. 그래서 크기는 측정한 RMS로 맞춘다.
    rng = np.random.default_rng(1)
    r = rng.uniform(-1, 1, 400000)
    from scipy.signal import lfilter
    y = lfilter([k], [1, -(1 - k)], r) + m * r
    g = np.sqrt((x ** 2).mean()) / np.sqrt((y[1000:] ** 2).mean())
    return k, m, g

def write_table(folder):
    print('/* noise_table.inc — generated by tools/gen_noise.py, do not edit.')
    print(' *')
    print(' * The noise of every key, as { k, m, g } of')
    print(' * out = g * (lowpass(r) + m * r), lowpass y += k * (r - y), r white')
    print(' * noise in -1..1 at 22050Hz, fitted to the spectrum of PICO-8 0.2.7\'s')
    print(' * .wav export (volume 7), in the units of pico8_wave().')
    print(' *')
    print(' * 키마다의 노이즈. out = g * (lowpass(r) + m * r)의 { k, m, g }이며,')
    print(' * PICO-8 0.2.7 .wav export(음량 7)의 스펙트럼에 맞췄다.')
    print(' */')
    print('static const float kNoiseFilter[64][3] = {')
    for key in range(64):
        k, m, g = fit('%s/noise_%d.wav' % (folder, key))
        print('    { %.5ff, %.5ff, %.5ff },   /* key %d */' % (k, m, g, key))
    print('};')

if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == 'cart':
        write_cart(sys.argv[2])
    elif len(sys.argv) == 3 and sys.argv[1] == 'table':
        write_table(sys.argv[2])
    else:
        sys.exit(__doc__)
