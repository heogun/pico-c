def octal_escapes(hexstr):
    return "".join("\\%03o" % b for b in bytes.fromhex(hexstr))


def main():
    assert len(MEASURED) == 256, len(MEASURED)

    out = []
    out.append("/* Generated by tools/gen_charset.py -- do not edit by hand.")
    out.append("   PICO-8 0.2.7 charset, measured through chr()/printh().")
    out.append("")
    out.append("   Byte -> UTF-8 glyph. NULL means the byte is passed through")
    out.append("   unchanged (printable ASCII plus tab/LF/CR); an empty string")
    out.append("   is the NUL byte, which stops the conversion (printh has")
    out.append("   C-string semantics on the oracle). Everything else -- the funny")
    out.append("   fonts, the graphics glyphs and emoji, hiragana/katakana -- maps")
    out.append("   to the glyph below. */")
    out.append("static const char *const kGlyphUTF8[256] = {")
    for c in range(256):
        h = MEASURED[c]
        if h == "":
            text = '""'
        elif h == "%02x" % c and (c in (9, 10, 13) or 32 <= c <= 126):
            text = "NULL"
        else:
            text = '"%s"' % octal_escapes(h)
        out.append("    %-28s /* %3d */" % (text + ",", c))
    out.append("};")
    out.append("")
    out.append("/* UTF-8 glyph -> charset byte, tried longest match first. This is")
    out.append("   what cart loading applies to source text: a matching sequence")
    out.append("   collapses into one charset byte, everything else stays as raw")
    out.append("   bytes. */")
    out.append("static const GlyphSeq kGlyphSeqs[] = {")
    seqs = sorted(
        ((bytes.fromhex(MEASURED[c]), c) for c in range(256)
         if MEASURED[c] and MEASURED[c] != "%02x" % c),
        key=lambda t: (-len(t[0]), t[1]))
    for seq, code in seqs:
        assert len(seq) >= 2
        out.append('    { "%s", %d, %d },' % (octal_escapes(seq.hex()), code, len(seq)))
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
