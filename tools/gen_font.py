#!/usr/bin/env python3
"""Generate src/font_table.inc from tools/font_dump.txt.

The dump was measured on PICO-8 0.2.7: for each charset code the cart prints
chr(c) at (0,0) in colour 7 and peeks the 8x6 pixel cell at 0x6000, so the
rows are the real built-in font bitmaps. Codes 9, 10 and 13 (tab, newline and
CR) move the cursor instead of drawing, and code 0 ends the string.

Rows are emitted the way src/gfx.cpp stores them: bit 7 is the leftmost pixel
of the cell. Narrow glyphs (1..31) only use bits 7..5, wide glyphs (128..255)
use bits 7..1 and are printed with an 8px advance.
"""

import re
import sys

SRC = "tools/font_dump.txt"
DST = "src/font_table.inc"


def load(path):
    glyphs = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"^(\d+):([01]{48})$", line.strip())
            if m:
                glyphs[int(m.group(1))] = m.group(2)
    return glyphs


def rows(bits):
    out = []
    for y in range(6):
        row = bits[y * 8 : (y + 1) * 8]
        mask = 0
        for x, px in enumerate(row):
            if px == "1":
                mask |= 1 << (7 - x)
        out.append(mask)
    out += [0, 0]
    return out


def emit(f, name, glyphs, first, count, comment):
    f.write("%s\nstatic const uint8_t %s[%d][8] = {\n" % (comment, name, count))
    for i in range(count):
        vals = rows(glyphs[first + i])
        f.write("    {%s},\n" % ",".join("0x%02x" % v for v in vals))
    f.write("};\n\n")


def main():
    glyphs = load(SRC)
    # tab, newline and CR move the cursor, they never draw: all-zero bitmaps.
    for c in (9, 10, 13):
        glyphs[c] = "0" * 48
    need = set(range(1, 256))
    missing = need - set(glyphs)
    if missing:
        sys.exit("missing glyphs: %s" % sorted(missing))
    with open(DST, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen_font.py from tools/font_dump.txt -- do not edit.\n"
                "   PICO-8's built-in glyphs, measured from the oracle's screen RAM. */\n\n")
        emit(f, "pico8_font_ctrl", glyphs, 1, 15,
             "/* 1bpp glyphs for control codes 1..15 (only code 5 draws). */")
        emit(f, "pico8_font_small", glyphs, 16, 16,
             "/* 1bpp glyphs for the funny-font codes 16..31, 3x5 in a 4x6 cell. */")
        emit(f, "pico8_font_wide", glyphs, 128, 128,
             "/* 1bpp glyphs for the wide codes 128..255, 7x5 in an 8x6 cell. */")


if __name__ == "__main__":
    main()
