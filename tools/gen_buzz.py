#!/usr/bin/env python3
"""gen_buzz.py — build src/buzz_table.inc from PICO-8's own .wav export.

The "buzz" filter of a sound effect changes the shape of the waveform in a
way that does not follow from a simple formula, so pico-c plays it from a
table: one period of every buzzed waveform, measured on PICO-8.

Two steps:

    tools/gen_buzz.py cart buzz.p8
        writes a cart whose sound effects 0..5 play waveform 0..5 with buzz
        on, key 24 (most notes are at least that high; the buzzed saw is a little
        quieter below it),
        volume 7, speed 64, and that exports them with export("buzz_%d.wav").
        Run it in a windowed PICO-8 with its own home folder (see
        platforms/macos/oracle_audio.sh), which leaves buzz_0.wav .. in
        <home>/carts.

    tools/gen_buzz.py table <dir with buzz_N.wav> > src/buzz_table.inc
        folds every recording on its period (key 24 = 84.28 samples at
        22050Hz; the period drifts against the samples, which gives sub-sample
        resolution), averages it into 256 points and rotates it so that it
        lines up with pico-c's plain waveform of the same number.  The values
        are in the units of pico8_wave(): a triangle at full volume peaks at
        0.5 (16122 in PICO-8's .wav files).

The phaser (7) is not measured: pico-c builds its buzz version from the
buzzed triangle, the way the plain phaser is built from the triangle.
Waveform 6 (noise) has no buzz table.

gen_buzz.py — PICO-8 자체의 .wav export로 src/buzz_table.inc를 만든다.

효과음의 "buzz" 필터는 파형 모양을 간단한 식으로 따라갈 수 없게 바꾸므로,
pico-c는 표로 연주한다: PICO-8에서 측정한, buzz가 걸린 파형마다 한 주기.
"cart" 단계는 파형 0..5에 buzz를 건 효과음(키 24, 음량 7, 속도 64)을
export("buzz_%d.wav")로 내보내는 카트를 쓰고, "table" 단계는 그 녹음을 주기로
접어 256점으로 평균 내고, pico-c의 같은 번호 기본 파형과 맞도록 회전한다.
값은 pico8_wave()의 단위다(최대 음량 삼각파의 정점이 0.5).
위상기(7)는 측정하지 않는다: 기본 위상기를 삼각파로 만들듯, buzz가 걸린
삼각파로 만든다. 노이즈(6)에는 표가 없다.
"""
import math
import struct
import sys
import wave

KEY = 24
POINTS = 256
WAVES = range(6)
PEAK = 16122.0          # a full volume triangle in PICO-8's .wav files

def plain(w, t):
    """pico-c's plain waveform w at phase t (same as pico8_wave())."""
    if w == 0:
        return (1 - abs(4 * t - 2)) * 0.5
    if w == 1:
        a = 0.875
        return (2 * t / a - 1 if t < a else 2 * (1 - t) / (1 - a) - 1) * 0.5
    if w == 2:
        return 0.653 * (t if t < 0.5 else t - 1)
    if w == 3:
        return 0.25 if t < 0.5 else -0.25
    if w == 4:
        return 0.25 if t < 0.316 else -0.25
    if w == 5:
        return (3 - abs(24 * t - 6) if t < 0.5 else 1 - abs(16 * t - 12)) / 9
    raise ValueError(w)

def write_cart(path):
    lines = []
    for i in range(64):
        notes = [(0, 0, 0, 0)] * 32
        mode = 0
        if i in WAVES:
            notes[0] = (KEY, i, 7, 0)
            mode = 4                       # buzz
        lines.append('%02x%02x%02x%02x' % (mode, 64, 0, 0) +
                     ''.join('%02x%x%x%x' % n for n in notes))
    with open(path, 'w') as f:
        f.write('pico-8 cartridge // http://www.pico-8.com\nversion 43\n'
                '__lua__\nexport("buzz_%d.wav")\n__sfx__\n' + '\n'.join(lines) + '\n')

def read(path):
    w = wave.open(path)
    data = w.readframes(w.getnframes())
    return struct.unpack('<%dh' % (len(data) // 2), data)

def fold_at(samples, period):
    sums = [0.0] * POINTS
    counts = [0] * POINTS
    for n in range(1000, 11000):
        k = int((n / period % 1.0) * POINTS)
        sums[k] += samples[n]
        counts[k] += 1
    return [s / c / PEAK * 0.5 if c else 0.0 for s, c in zip(sums, counts)]

def fold(samples):
    """Fold on the period that gives the sharpest shape: PICO-8's pitch is
    a hair away from the ideal one, and folding 60 periods on the ideal
    period would smear the edges.
    PICO-8의 피치는 이상적인 값과 아주 조금 다르므로, 모양이 가장 뚜렷해지는
    주기로 접는다(이상적인 주기로 60주기를 접으면 모서리가 뭉개진다)."""
    ideal = 22050 / (440 * 2 ** ((KEY - 33) / 12))
    best = None
    for i in range(-40, 41):
        table = fold_at(samples, ideal * (1 + i * 0.00005))
        sharp = sum(v * v for v in table)
        if best is None or sharp > best[0]:
            best = (sharp, table)
    return best[1]

def align(table, w):
    ref = [plain(w, (k + 0.5) / POINTS) for k in range(POINTS)]
    best = max(range(POINTS),
               key=lambda s: sum(table[(k - s) % POINTS] * ref[k] for k in range(POINTS)))
    return [table[(k - best) % POINTS] for k in range(POINTS)]

def write_table(folder):
    print('/* buzz_table.inc — generated by tools/gen_buzz.py, do not edit.')
    print(' *')
    print(' * One period of every waveform with the buzz filter on, measured from')
    print(' * PICO-8 0.2.7\'s .wav export (key %d, volume 7), %d points, in the' % (KEY, POINTS))
    print(' * units of pico8_wave().')
    print(' *')
    print(' * buzz 필터를 켠 파형마다 한 주기. PICO-8 0.2.7의 .wav export에서 측정했다')
    print(' * (키 %d, 음량 7), %d점, pico8_wave() 단위.' % (KEY, POINTS))
    print(' */')
    print('static const float kBuzzTable[%d][%d] = {' % (len(WAVES), POINTS))
    for w in WAVES:
        table = align(fold(read('%s/buzz_%d.wav' % (folder, w))), w)
        print('    { /* waveform %d */' % w)
        for i in range(0, POINTS, 8):
            print('        ' + ' '.join('%8.5ff,' % v for v in table[i:i + 8]))
        print('    },')
    print('};')

if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == 'cart':
        write_cart(sys.argv[2])
    elif len(sys.argv) == 3 and sys.argv[1] == 'table':
        write_table(sys.argv[2])
    else:
        sys.exit(__doc__)
